"""
summarize.py -- v4 Phase 2: the tables of REPORT.md, computed from the evaluation JSON files.

Reads
  ../02-redesign/output/<raw>/        Phase 1b methods (our methods), written by 02-redesign/evaluate.py
  output/<raw>/                       Phase 2 base-paper methods, written by 02-redesign/evaluate.py --phase2
(<raw> = eval_raw by default; --raw-dir NAME reads a re-run instead, e.g. to check it gives the same tables).

Writes output/eval_per_seed.csv and output/eval_summary.md (or ..._<NAME>.md / .csv with --raw-dir).

Same statistics as 02-redesign/summarize.py (PLAN 02 Section 5): mean over seeds; "±" = 95% confidence half-width
(t with n − 1 degrees of freedom); differences with a 95% Welch CI. Methods with fewer seeds (RMAPPO: 6, Stage 3
only) use the seeds they have; a missing stage is shown as "not run".

Rounding: one decimal, half up (28.85 -> 28.9). Each seed's success is k/200, so the mean over 10 seeds is often
exactly x.x5; plain float formatting then rounds 28.85 up or down depending on float noise. f1() removes that.

Usage:  python summarize.py [--raw-dir NAME]
"""
import os, sys, json, glob
from decimal import Decimal, ROUND_HALF_UP
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
PHASE1B = os.path.join(HERE, '..', '02-redesign')
# the Phase 1b statistics, unchanged; loaded by path because that file is also called summarize.py
import importlib.util
_spec = importlib.util.spec_from_file_location('summarize_phase1b', os.path.join(PHASE1B, 'summarize.py'))
_p1b = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_p1b)
welch, verdict = _p1b.welch, _p1b.verdict

OURS = ['mappo-pah', 'fixed-weight-mappo', 'tau-rule-mappo', 'mappo-pah-no-hungarian', 'plain-mappo']
BASE = ['igat-style', 'da-mappo-2d', 'mappo', 'ippo', 'rmappo']
NAMES = {'mappo-pah': 'MAPPO + PAH', 'fixed-weight-mappo': 'Fixed-weight MAPPO',
         'tau-rule-mappo': 'Hand-coded τ-rule MAPPO', 'mappo-pah-no-hungarian': 'MAPPO + PAH (Hungarian off)',
         'plain-mappo': 'Plain MAPPO', 'igat-style': 'IGAT-style MAPPO', 'da-mappo-2d': 'DA-MAPPO (2D)',
         'mappo': 'MAPPO', 'ippo': 'IPPO', 'rmappo': 'RMAPPO'}
# controlled steps from DA-MAPPO (2D) to MAPPO + PAH (REPORT.md, "Where the Stage 3 gap comes from")
STEPS = [('plain-mappo', 'da-mappo-2d', 'Conflict-graph observation'),
         ('fixed-weight-mappo', 'plain-mappo', 'Two value heads (mission + safety)'),
         ('mappo-pah', 'fixed-weight-mappo', 'PAH learned α')]


def f1(x, sign=False):
    """x to one decimal, half up, after removing float noise below 1e-6."""
    v = Decimal('{:.6f}'.format(x)).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)
    return ('+' if sign and v >= 0 else '') + str(v)


def ci(d, lo, hi):
    return '{} [{}, {}]'.format(f1(d, True), f1(lo, True), f1(hi, True))


def load(raw):
    files = glob.glob(os.path.join(PHASE1B, 'output', raw, '*.json')) + glob.glob(os.path.join(HERE, 'output', raw, '*.json'))
    rows = [json.load(open(f)) for f in sorted(files)]
    return {(r['stage'], r['method'], r['seed']): r for r in rows}


def main():
    raw = sys.argv[sys.argv.index('--raw-dir') + 1] if '--raw-dir' in sys.argv else 'eval_raw'
    tag = '' if raw == 'eval_raw' else '_' + raw
    R = load(raw)

    def get(st, m, k):
        """One value per seed (sorted by seed) of field k; empty if the method was not run at that stage."""
        return np.array([R[(st, m, s)][k] for s in sorted(s for (a, b, s) in R if a == st and b == m)], dtype=float)

    def half(x):
        return stats.t.ppf(0.975, len(x) - 1) * x.std(ddof=1) / np.sqrt(len(x)) if len(x) > 1 else float('nan')

    with open(os.path.join(HERE, 'output', 'eval_per_seed{}.csv'.format(tag)), 'w') as f:
        f.write('stage,method,seed,success,collision,timeout,coll_drone_drone,coll_drone_obstacle,coll_both,T_ave,L_ave\n')
        for (st, m, s), r in sorted(R.items()):
            f.write('{},{},{},{:.3f},{:.3f},{:.3f},{},{},{},{:.2f},{:.2f}\n'.format(
                st, m, s, r['success'], r['collision'], r['timeout'], r['coll_drone_drone'], r['coll_drone_obstacle'],
                r['coll_both'], r['T_ave'], r['L_ave']))

    L = ['# Phase 2 — evaluation summary', '',
         'Generated by `03-base-paper-baselines/summarize.py` from `{}/` (Phase 1b and Phase 2). Deterministic, 200 '
         'episodes per model, evaluation seed 7001.'.format(raw), '']
    seeds = lambda st, m: len(get(st, m, 'success'))

    L += ['## Table 1 — success, collision, timeout (%)', '',
          '| Method | Seeds S2 / S3 | S2 Success | S2 Coll. | S2 Timeout | S3 Success | S3 Coll. | S3 Timeout |',
          '|---|---|---|---|---|---|---|---|']
    for m in OURS + BASE:
        cells = []
        for st in (2, 3):
            s = get(st, m, 'success') * 100
            if len(s) == 0:
                cells += ['not run', '', '']
                continue
            cells += ['{} ± {}'.format(f1(s.mean()), f1(half(s))), f1((get(st, m, 'collision') * 100).mean()),
                      f1((get(st, m, 'timeout') * 100).mean())]
        L.append('| {} | {} / {} | {} |'.format(NAMES[m], seeds(2, m), seeds(3, m), ' | '.join(cells)))

    L += ['', '## Table 2 — speed and path (successful episodes only), collisions summed over all test episodes', '',
          '| Method | S2 T_ave | S2 L_ave | S2 Hits D–D / D–O | S3 T_ave | S3 L_ave | S3 Hits D–D / D–O |',
          '|---|---|---|---|---|---|---|']
    for m in OURS + BASE:
        cells = []
        for st in (2, 3):
            if seeds(st, m) == 0:
                cells += ['not run', '', '']
                continue
            T, Lp = get(st, m, 'T_ave'), get(st, m, 'L_ave')
            fmt = lambda v: '—' if np.all(np.isnan(v)) else str(Decimal('{:.6f}'.format(np.nanmean(v))).quantize(Decimal('1'), rounding=ROUND_HALF_UP))
            cells += [fmt(T), fmt(Lp), '{:.0f} / {:.0f}'.format(get(st, m, 'coll_drone_drone').sum(),
                                                                get(st, m, 'coll_drone_obstacle').sum())]
        L.append('| {} | {} |'.format(NAMES[m], ' | '.join(cells)))

    L += ['', '## Table 3 — MAPPO + PAH minus each method (success points, 95% Welch CI)', '',
          '| Compared with | Stage 2 | Reading | Stage 3 | Reading |', '|---|---|---|---|---|']
    for m in OURS[1:] + BASE:
        cells = []
        for st in (2, 3):
            if seeds(st, m) == 0:
                cells += ['not run', '']
                continue
            d, lo, hi = welch(get(st, 'mappo-pah', 'success') * 100, get(st, m, 'success') * 100)
            cells += [ci(d, lo, hi), verdict(lo, hi)]
        L.append('| {} | {} |'.format(NAMES[m], ' | '.join(cells)))

    L += ['', '## Gap breakdown — controlled steps from DA-MAPPO (2D) to MAPPO + PAH', '',
          '| Step | From → to | Stage 2 | Stage 3 |', '|---|---|---|---|']
    for a, b, q in STEPS:
        cells = [ci(*welch(get(st, a, 'success') * 100, get(st, b, 'success') * 100)) for st in (2, 3)]
        L.append('| {} | {} → {} | {} |'.format(q, NAMES[b], NAMES[a], ' | '.join(cells)))
    cells = [ci(*welch(get(st, 'da-mappo-2d', 'success') * 100, get(st, 'mappo', 'success') * 100)) for st in (2, 3)]
    L += ['', 'Real-time re-assignment (DA-MAPPO (2D) − MAPPO): Stage 2 {}, Stage 3 {}.'.format(*cells), '']

    open(os.path.join(HERE, 'output', 'eval_summary{}.md'.format(tag)), 'w').write('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
