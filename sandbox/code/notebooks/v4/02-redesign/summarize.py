"""
summarize.py -- v4 Phase 1b, Step 5: tables and the PLAN Section 5 comparisons from output/eval_raw/.

Reading rule (PLAN.md Section 5, fixed before any result): difference in mean success over the 10 seeds with a
95% Welch confidence interval.
  CI entirely above 0 -> MAPPO + PAH better;  CI entirely below 0 -> worse;
  CI inside +-3 points and containing 0 -> equivalent within 3 points;  otherwise -> inconclusive.

Writes output/eval_per_seed.csv and output/eval_summary.md.
"""
import os, json, glob
import numpy as np
from scipy import stats

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'output')
METHODS = ['plain-mappo', 'fixed-weight-mappo', 'tau-rule-mappo', 'mappo-pah', 'mappo-pah-no-hungarian']
NAMES = {'plain-mappo': 'Plain MAPPO', 'fixed-weight-mappo': 'Fixed-weight MAPPO',
         'tau-rule-mappo': 'Hand-coded τ-rule MAPPO', 'mappo-pah': 'MAPPO + PAH',
         'mappo-pah-no-hungarian': 'MAPPO + PAH (Hungarian off)'}
COMPARISONS = [('mappo-pah', 'fixed-weight-mappo', 'primary question (asked at Stage 3)'),
               ('mappo-pah', 'tau-rule-mappo', 'does learning α add anything over the formula'),
               ('mappo-pah', 'plain-mappo', 'does arbitration add anything at all'),
               ('mappo-pah', 'mappo-pah-no-hungarian', 'Hungarian on vs off'),
               ('fixed-weight-mappo', 'plain-mappo', 'separate value heads')]


def load():
    rows = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(OUT, 'eval_raw', '*.json')))]
    return {(r['stage'], r['method'], r['seed']): r for r in rows}


def welch(x, y):
    x, y = np.asarray(x, float), np.asarray(y, float)
    va, vb = x.var(ddof=1) / len(x), y.var(ddof=1) / len(y)
    df = (va + vb) ** 2 / (va ** 2 / (len(x) - 1) + vb ** 2 / (len(y) - 1))
    d = x.mean() - y.mean()
    h = stats.t.ppf(0.975, df) * np.sqrt(va + vb)
    return d, d - h, d + h


def verdict(lo, hi):
    if lo > 0:
        return 'better'
    if hi < 0:
        return 'worse'
    if lo >= -3 and hi <= 3:
        return 'equivalent within 3 points'
    return 'inconclusive'


def main():
    R = load()
    get = lambda st, m, k: np.array([R[(st, m, s)][k] for s in sorted(s for (a, b, s) in R if a == st and b == m)])
    with open(os.path.join(OUT, 'eval_per_seed.csv'), 'w') as f:
        f.write('stage,method,seed,success,collision,timeout,coll_drone_drone,coll_drone_obstacle,coll_both,'
                'T_ave,L_ave,alpha_danger,alpha_safe,tau_set_by_obstacle\n')
        for (st, m, s), r in sorted(R.items()):
            f.write('{},{},{},{:.3f},{:.3f},{:.3f},{},{},{},{:.2f},{:.2f},{:.4f},{:.4f},{:.3f}\n'.format(
                st, m, s, r['success'], r['collision'], r['timeout'], r['coll_drone_drone'], r['coll_drone_obstacle'],
                r['coll_both'], r['T_ave'], r['L_ave'], r['alpha_danger'], r['alpha_safe'], r['tau_set_by_obstacle']))

    L = ['# Phase 1b — Step 5 final evaluation', '',
         'Deterministic, 200 episodes per model, evaluation seed 7001, 10 seeds (42–51) per method and stage. '
         'Generated by `summarize.py` from `output/eval_raw/` (written by `evaluate.py`).', '']
    for st in (2, 3):
        n = {2: '5 drones, 10 discs', 3: '8 drones, 20 discs'}[st]
        L += ['## Stage {} ({})'.format(st, n), '',
              '| Method | Success % | Collision % | Timeout % | T_ave (steps) | L_ave (units) | Success, worst–best seed |',
              '|---|---|---|---|---|---|---|']
        for m in METHODS:
            s = get(st, m, 'success') * 100
            L.append('| {} | {:.1f} | {:.1f} | {:.1f} | {:.1f} | {:.1f} | {:.1f}–{:.1f} |'.format(
                NAMES[m], s.mean(), get(st, m, 'collision').mean() * 100, get(st, m, 'timeout').mean() * 100,
                np.nanmean(get(st, m, 'T_ave')), np.nanmean(get(st, m, 'L_ave')), s.min(), s.max()))
        L += ['', 'T_ave and L_ave: successful episodes only (steps to finish; mean path length per drone).', '',
              '**Comparisons (success, percentage points; 95% Welch CI over 10 vs 10 seeds; PLAN §5 rule):**', '',
              '| Comparison | Question | Difference | 95% CI | Reading |', '|---|---|---|---|---|']
        for a, b, q in COMPARISONS:
            d, lo, hi = welch(get(st, a, 'success') * 100, get(st, b, 'success') * 100)
            L.append('| {} − {} | {} | {:+.1f} | [{:+.1f}, {:+.1f}] | {} |'.format(NAMES[a], NAMES[b], q, d, lo, hi,
                                                                               verdict(lo, hi)))
        L += ['', '**Collisions by kind (sum over 10 seeds × 200 episodes):**', '',
              '| Method | drone–obstacle | drone–drone | both |', '|---|---|---|---|']
        for m in METHODS:
            L.append('| {} | {} | {} | {} |'.format(NAMES[m], get(st, m, 'coll_drone_obstacle').sum(),
                                                    get(st, m, 'coll_drone_drone').sum(), get(st, m, 'coll_both').sum()))
        L += ['', '**Mechanism — α by hazard τ (mean over seeds; τ = 3 means nothing within the 3-step horizon):**', '',
              '| Method | τ < 1 (danger) | 1 ≤ τ < 2 | 2 ≤ τ < 3 | τ = 3 (safe) | τ set by an obstacle |',
              '|---|---|---|---|---|---|']
        for m in METHODS:
            b = np.nanmean(np.array([R[k]['alpha_tau_bins'] for k in R if k[0] == st and k[1] == m]), axis=0)
            L.append('| {} | {:.2f} | {:.2f} | {:.2f} | {:.2f} | {:.0f}% |'.format(
                NAMES[m], *b, get(st, m, 'tau_set_by_obstacle').mean() * 100))
        L.append('')
    open(os.path.join(OUT, 'eval_summary.md'), 'w').write('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
